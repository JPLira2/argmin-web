"""The dither for the plates' gradients: a seamless tile of blue noise around mid-grey.

    python tools/grain.py

A gentle gradient over a large plate has only a few 8-bit shades to spend, so it breaks into visible steps
(banding), and Safari and Firefox barely dither gradients themselves. Laid over a gradient with soft-light,
this tile moves each pixel by a shade or two either way: the steps dissolve and the colours stay as they are,
since mid-grey under soft-light changes nothing. Blue noise (white noise with its low frequencies taken out)
has no clumps, so at this strength it reads as a finer surface, not as grain. Filtered in the frequency domain,
so the tile repeats without a seam. Writes assets/grain.png (128 x 128, 8-bit grey).
"""
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from PIL import Image

N, STD, SEED = 128, 6.0, 7
out = Path(__file__).resolve().parent.parent / 'assets' / 'grain.png'

rng = np.random.default_rng(SEED)
f = np.fft.fftfreq(N)
r = np.hypot(*np.meshgrid(f, f))
spectrum = np.fft.fft2(rng.standard_normal((N, N))) * (1 - np.exp(-(r / 0.16) ** 2))   # the low frequencies out
noise = np.real(np.fft.ifft2(spectrum))
noise = (noise - noise.mean()) / noise.std() * STD + 128
Image.fromarray(np.clip(np.round(noise), 0, 255).astype(np.uint8), 'L').save(out, optimize=True)
origin = ('Origin: generated by tools/grain.py (seeded blue noise around mid-grey, the dither for the plates\' '
          'gradients); no image generation.')
out.with_name(out.name + '.json').write_text(json.dumps({'prompt': origin, 'createdAt': datetime.now(timezone.utc).isoformat(timespec='seconds')}, indent=2) + '\n', encoding='utf-8')
print(f'{out.name}: {N} x {N}, {out.stat().st_size // 1024} KB')
